    constraint [FK_Content_QuestionReply_Audio] foreign key ([AudioId]) references [Framework].[AudioFile] ([Id]),
    constraint [FK_Content_QuestionReply_Image] foreign key ([ImageId]) references [Framework].[ImageFile] ([Id]),
    constraint [FK_Content_QuestionReply_Pdf] foreign key ([PdfId]) references [Framework].[PdfFile] ([Id]),
    constraint [FK_Content_QuestionReply_Video] foreign key ([VideoId]) references [Framework].[VideoFile] ([Id]),
    constraint [FK_Content_QuestionReply_Postal] foreign key ([PostalId]) references [Framework].[UsaPostal] ([Id]),
);