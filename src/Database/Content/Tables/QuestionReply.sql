create table [Content].[QuestionReply] (
    [Id] uniqueidentifier not null,
    [VersionOf] uniqueidentifier not null,
    [Updated] datetimeoffset(7) default(sysdatetimeoffset()) not null,
    [UpdatedBy] uniqueidentifier not null,
    [IsDeleted] bit default(0) not null,
    [SurveyReplyId] uniqueidentifier null,
    [QuestionId] uniqueidentifier not null,
    [Submitted] datetimeoffset(7) default(sysdatetimeoffset()) not null,
    [BoolValue] bit null,
    [TextValue] nvarchar(max) null,
    [HtmlValue] nvarchar(max) null,
    [DateValue] date null,
    [TimeValue] time null,
    [DateTimeValue] datetimeoffset(7) null,
    [IntegerValue] int null,
    [DecimalValue] real null,
    [CurrencyValue] real null,
    [OtherBoolValue] bit default(0) null,
    [OtherTextValue] nvarchar(150) null,
    [AudioId] uniqueidentifier null,
    [ImageId] uniqueidentifier null,
    [PdfId] uniqueidentifier null,
    [VideoId] uniqueidentifier null,
    [PostalId] uniqueidentifier null,
    constraint [PK_Content_QuestionReply] primary key clustered ([Id]),
